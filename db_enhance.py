def seed_role_permissions(conn):
    count = conn.execute("SELECT COUNT(*) AS n FROM RolePermissions").fetchone()["n"]
    if int(count) > 0:
        return
    rows = []
    for role, codes in permissions.DEFAULT_ROLE_PERMISSIONS.items():
        for code in codes:
            rows.append((role, code))
    conn.executemany(
        "INSERT INTO RolePermissions (RoleName, PermissionCode) VALUES (?, ?) ON CONFLICT DO NOTHING",
        rows,
    )


def get_role_permissions(role=None):
    with connect() as conn:
        if role:
            rows = conn.execute(
                "SELECT PermissionCode FROM RolePermissions WHERE RoleName = ? ORDER BY PermissionCode",
                (role,),
            ).fetchall()
            return [row["PermissionCode"] for row in rows]
        rows = conn.execute(
            "SELECT RoleName, PermissionCode FROM RolePermissions ORDER BY RoleName, PermissionCode"
        ).fetchall()
    matrix = {r: [] for r in permissions.DEFAULT_ROLE_PERMISSIONS}
    for row in rows:
        matrix.setdefault(row["RoleName"], []).append(row["PermissionCode"])
    return matrix


def set_role_permissions(role, codes):
    if role not in permissions.DEFAULT_ROLE_PERMISSIONS:
        raise ValueError("Invalid role.")
    clean = []
    for code in codes or []:
        code = str(code).strip()
        if code in permissions.ALL_PERMISSIONS and code not in clean:
            clean.append(code)
    with _WRITE_LOCK, connect() as conn:
        conn.execute("DELETE FROM RolePermissions WHERE RoleName = ?", (role,))
        conn.executemany(
            "INSERT INTO RolePermissions (RoleName, PermissionCode) VALUES (?, ?)",
            [(role, c) for c in clean],
        )
    return get_role_permissions(role)


def permission_set_for(role):
    codes = get_role_permissions(role)
    if codes:
        return set(codes)
    return set(permissions.DEFAULT_ROLE_PERMISSIONS.get(role, []))


