def _tables(conn):
    if conn.postgres:
        rows = conn.execute(
            "SELECT tablename AS n FROM pg_tables WHERE schemaname = 'public'"
        )
        return {row["n"] for row in rows}
    return {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}


def program_extra_fields(row, keys, enrollees, attendance):
    category = "Administrative"
    if "ProgramCategory" in keys and row["ProgramCategory"]:
        category = row["ProgramCategory"]
    elif row["ProgramType"] == "Health":
        category = "Health"
    attended_map = attendance.get(row["ProgramId"], {})
    return {
        "category": category,
        "attendance": attended_map,
        "beneficiaries": enrollees.get(row["ProgramId"], []),
    }


def load_enrollee_maps(conn):
    enrollees = {}
    attendance = {}
    cols = _table_columns(conn, "ProgramEnrollees")
    for row in conn.execute("SELECT * FROM ProgramEnrollees ORDER BY EnrolleeId"):
        enrollees.setdefault(row["ProgramId"], []).append(row["RecordId"])
        if "Attended" in cols:
            attendance.setdefault(row["ProgramId"], {})[row["RecordId"]] = bool(row["Attended"])
    return enrollees, attendance


