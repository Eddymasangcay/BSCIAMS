def _nullable_float(value):
    if value is None or value == "":
        return None
    return _as_float(value, "measurement")


def seed_default_documents_if_empty(conn):
    """Create baseline document checklist rows for seniors when none exist."""
    if "SeniorDocuments" not in _tables(conn):
        return
    count = int(conn.execute("SELECT COUNT(*) AS n FROM SeniorDocuments").fetchone()["n"])
    if count > 0:
        return
    seniors = conn.execute("SELECT RecordId FROM SeniorCitizens").fetchall()
    rows = []
    for senior in seniors:
        for dtype in DOCUMENT_TYPES:
            rows.append((
                f"DOC-{uuid.uuid4().hex[:10].upper()}",
                senior["RecordId"],
                dtype,
                "Missing",
                "",
                "",
                "",
                "",
                _now(),
            ))
    if rows:
        conn.executemany(
            """
            INSERT INTO SeniorDocuments (
                DocumentId, RecordId, DocumentType, DocumentStatus, SubmittedAt,
                VerifiedAt, VerifiedBy, Remarks, DateUpdated
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            rows,
        )


